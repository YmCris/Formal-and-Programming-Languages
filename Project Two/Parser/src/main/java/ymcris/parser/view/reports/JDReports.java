    // SPECIFIC METHODS --------------------------------------------------------
    private void addErrors() {
        tblErrors = (DefaultTableModel) tblErrorReport.getModel();
        for (Word error : reportsController.getErrors()) {
            tblErrors.addRow(new Object[]{error.getLexeme(), "x", error.getRow(), error.getColumn()});
        }
    }

    private void addTokens() {
        tblTokens = (DefaultTableModel) tblTokenReport.getModel();
        for (Token token : reportsController.getReportTokens()) {
            tblTokens.addRow(new Object[]{token.getTokenType().getName(), token.getLexeme(), token.getRow(), token.getColumn()});
        }
    }

    private void addLexemes() {
        tblLexemes = (DefaultTableModel) tblLexemeCount.getModel();
        for (Token token : reportsController.getReportTokens()) {
            tblLexemes.addRow(new Object[]{token.getLexeme(), token.getTokenType(), "x"});
        }
    }

