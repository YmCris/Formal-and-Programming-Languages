    // CONSTRUCTOR METHOD ------------------------------------------------------
    public JDDiagram(String token) {
        initComponents();
        this.token = token;
        this.setModal(true);
        this.setTitle("DIAGRAM");
        this.setResizable(false);
        this.setLocationRelativeTo(null);
        JPanel container = new JPanel(new FlowLayout(FlowLayout.LEFT, 10, 10));
        container.setBackground(new java.awt.Color(51, 51, 51));
        doDiagram(container);
        JScrollPane scroll = new JScrollPane(container,
                JScrollPane.VERTICAL_SCROLLBAR_NEVER,
                JScrollPane.HORIZONTAL_SCROLLBAR_AS_NEEDED);
        scroll.setBackground(new java.awt.Color(51, 51, 51));
        this.setContentPane(scroll);

    }

    // SPECIFIC METHODS --------------------------------------------------------
    private void doDiagram(JPanel container) {
        char[] characters = token.toCharArray();
        for (int i = 0; i < characters.length; i++) {
            JPState pnl = new JPState(i, characters[i]);
            if (i == characters.length - 1) {
                pnl.changeArrow();
            }
            container.add(pnl);
        }
    }

